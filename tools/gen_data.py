import re
#!/usr/bin/env python3
"""Генерує include/gen_data.h з data/*.json (області, міста, райони, вулиці, правила аналізу).
Запускається автоматично PlatformIO перед збіркою (extra_scripts = pre:tools/gen_data.py),
або вручну: python3 tools/gen_data.py
"""
import glob, json, os

try:
    Import("env")  # noqa: F821  (PlatformIO)
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except Exception:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

DATA = os.path.join(ROOT, "data")
import sys
sys.path.insert(0, os.path.join(ROOT, "server"))
from textnorm import fold_kw  # noqa: E402  — та сама нормалізація, що utf8Fold() у прошивці
OUT = os.path.join(ROOT, "include", "gen_data.h")


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    loc = json.load(open(os.path.join(DATA, "locations.json"), encoding="utf-8"))
    rules = json.load(open(os.path.join(DATA, "rules.json"), encoding="utf-8"))
    streets = {}
    for p in glob.glob(os.path.join(DATA, "streets_*.json")):
        s = json.load(open(p, encoding="utf-8"))
        streets[s["city"]] = s["streets"]

    crp = os.path.join(DATA, "city_regions.json")
    city_reg = json.load(open(crp, encoding="utf-8")) if os.path.exists(crp) else {}
    o = []
    w = o.append
    w("// AUTO-GENERATED by tools/gen_data.py from data/*.json — edit JSON, not this file\n#pragma once\n#include \"data_types.h\"\n")
    n = [0]

    def kwlist(words):
        n[0] += 1
        name = f"KW_{n[0]}"
        words = [("=" + fold_kw(x[1:])) if x.startswith("=") else fold_kw(x) for x in words]
        w(f"static const char* const {name}[] = {{{', '.join(cstr(x) for x in words)}}};")
        return name, len(words)

    w(f"#define OBLAST_COUNT {len(loc['oblasts'])}")
    w("static const OblastDef OBLASTS[OBLAST_COUNT] = {")
    for ob in loc["oblasts"]:
        w(f"  {{{cstr(ob['name'])}, {cstr(ob['short'])}, {ob['uid']}, {cstr(ob['ubilling'])}}},")
    w("};\n")

    # rules
    tnames = []
    for t in rules["threats"]:
        k, c = kwlist(t["kw"])
        fk, fc = kwlist(t.get("fuzzy", [])) if t.get("fuzzy") else ("nullptr", 0)
        mk, mc = kwlist(t["mask"]) if t.get("mask") else ("nullptr", 0)
        tnames.append((t, k, c, fk, fc, mk, mc))
    w(f"#define THREAT_COUNT {len(tnames)}")
    w("static const ThreatDef THREATS[THREAT_COUNT] = {")
    for t, k, c, fk, fc, mk, mc in tnames:
        lvl = 2 if t.get("level") == "red" else 1
        cap = {"yellow": 1, "orange": 2}.get(t.get("cap"), 0)   # Level: 1 жовтий, 2 помаранчевий
        w(f"  {{{cstr(t['type'])}, {cstr(t['label'])}, {cstr(t.get('kind', t['label']))}, {t['weight']}, {lvl}, {k}, {c}, {fk}, {fc}, {mk}, {mc}, {cap}}},")
    w("};")
    pl = []
    for p_ in rules.get("places", []):
        k, c = kwlist(p_["kw"])
        pl.append(f"  {{{cstr(p_['n'])}, {p_['lat']}f, {p_['lon']}f, {k}, {c}}},")
    w(f"#define PLACE_COUNT {len(pl)}")
    w("static const PlaceDef PLACES[PLACE_COUNT] = {\n" + "\n".join(pl) + "\n};")
    for key in ("approach", "escalate", "clear", "ignore", "unknown_dir"):
        k, c = kwlist(rules[key])
        w(f"static const WordList RULE_{key.upper()} = {{{k}, {c}}};")
    w("")

    city_lines = []
    for ci in loc["cities"]:
        cid = ci["id"]
        ck, cc = kwlist(ci["keywords"])
        dname = "nullptr"
        if ci["districts"]:
            dl = []
            for d in ci["districts"]:
                k, c = kwlist(d["keywords"] + [d["name"].lower()])
                dl.append(f"  {{{cstr(d['id'])}, {cstr(d['name'])}, {d['sector']}, {k}, {c}}},")
            dname = f"DIST_{cid}"
            w(f"static const DistrictDef {dname}[] = {{\n" + "\n".join(dl) + "\n};")
        sname, sc = "nullptr", 0
        st = rules.get("settlements", {}).get(cid, [])
        if st:
            sl = []
            for s in st:
                k, c = kwlist(s["kw"])
                sl.append(f"  {{{k}, {c}, {s['bearing']}, {s['km']}}},")
            sname, sc = f"SETTL_{cid}", len(st)
            w(f"static const SettlementDef {sname}[] = {{\n" + "\n".join(sl) + "\n};")
        stn, stc = "nullptr", 0
        if cid in streets:
            ids = [d["id"] for d in ci["districts"]]
            rows = []
            for name, did in streets[cid]:
                if did not in ids:
                    raise SystemExit(f"street {name}: unknown district {did}")
                rows.append(f"  {{{cstr(name)}, {ids.index(did)}}},")
            stn, stc = f"STREETS_{cid}", len(rows)
            w(f"static const StreetDef {stn}[] = {{\n" + "\n".join(rows) + "\n};")
        city_lines.append(
            f"  {{{cstr(cid)}, {cstr(ci['name'])}, {ci['oblast']}, {ci['lat']}f, {ci['lon']}f, {cstr(ci['channel'])}, "
            f"{ck}, {cc}, {dname}, {len(ci['districts'])}, {sname}, {sc}, {stn}, {stc}, {city_reg.get(cid, -1)}}},")
    w(f"\n#define CITY_COUNT {len(city_lines)}")
    w("static const CityDef CITIES[CITY_COUNT] = {\n" + "\n".join(city_lines) + "\n};")

    # згадки областей (для загальнонаціональних каналів)
    okw = rules.get("oblast_kw", {})
    ol = []
    for i in range(len(loc["oblasts"])):
        if okw.get(str(i)):
            k, c = kwlist(okw[str(i)])
            ol.append(f"  {{{k}, {c}}},")
        else:
            ol.append("  {nullptr, 0},")
    w("static const WordList OBLAST_KW[OBLAST_COUNT] = {\n" + "\n".join(ol) + "\n};")

    # Telegram-канали (data/channels.json) — порядок = біт у масці налаштувань
    chj = json.load(open(os.path.join(DATA, "channels.json"), encoding="utf-8"))["channels"]
    cl = []
    for ch in chj:
        sc = {"national": 0, "oblast": 1, "city": 2}[ch["scope"]]
        mask = 0
        for ob_ in ch.get("oblasts", []):
            mask |= 1 << ob_
        nm = re.sub(r"[^0-9A-Za-zА-Яа-яІіЇїЄєҐґ .,:()|/'-]", "", ch["name"]).strip(" |")
        nm = re.sub(r" +", " ", nm)
        cl.append(f"  {{{cstr(ch['id'])}, {cstr(nm)}, {sc}, {mask}u, {cstr(ch.get('home') or '')}, "
                  f"{int(round(ch['weight'] * 100))}, {1 if ch.get('default') else 0}}},")
    w(f"#define CHANNEL_COUNT {len(cl)}")
    w("static const ChannelDef CHANNELS[CHANNEL_COUNT] = {\n" + "\n".join(cl) + "\n};")

    # графіки відключень
    out = json.load(open(os.path.join(DATA, "outages.json"), encoding="utf-8"))
    w(f"\n#define OUTAGE_GROUP_COUNT {len(out['groups'])}")
    w("static const char* const OUTAGE_GROUPS[] = {" + ", ".join(cstr(g) for g in out["groups"]) + "};")
    w(f"#define OUTAGE_PROV_COUNT {len(out['providers'])}")
    w("static const OutageProvDef OUTAGE_PROVS[OUTAGE_PROV_COUNT] = {")
    for pr in out["providers"]:
        mask = sum(1 << o for o in pr["oblasts"])
        w(f"  {{{cstr(pr['id'])}, {cstr(pr['name'])}, {1 if pr['type'] == 'yasno' else 0}, {cstr(pr['url'])}, {mask}u}},")
    w("};")

    text = "\n".join(o) + "\n"
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if old != text:
        open(OUT, "w", encoding="utf-8").write(text)
        print("gen_data: include/gen_data.h updated")


main()
