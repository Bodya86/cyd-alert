#!/usr/bin/env python3
"""Генерує include/map_data.h: RLE-растр районів України (139 районів + м. Київ + м. Севастополь).

Значення пікселя: індекс району (0..MAP_REGION_COUNT-1), MAP_RBORDER — межа районів,
MAP_BORDER — межа областей, MAP_BG — фон. Для кожного району: індекс області (порядок alerts.in.ua IoT),
UID alerts.in.ua (0 — немає окремого UID: Крим, Київ, Севастополь, ЧЗВ) і назва.

  pip install pillow && python3 tools/gen_map.py
Геометрія: tools/ukraine_adm2.geojson (OCHA COD-AB, CC BY 3.0 IGO, спрощено tools/simplify_adm2.py)
"""
import json, math, os
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
W, H = 240, 162
PAD = 3
SS = 4
BG, BORDER, RBORDER = 255, 254, 253
KYIV, SEVAS = 9, 18   # індекси областей-міст

gj = json.load(open(os.path.join(HERE, "ukraine_adm2.geojson"), encoding="utf-8"))
feats = gj["features"]
N = len(feats)
assert N < RBORDER
LAT0 = 48.5


def proj(lon, lat):
    return lon * math.cos(math.radians(LAT0)), -lat


def rings(f):
    return [poly[0] for poly in f["geometry"]["coordinates"]]


pts = [proj(*c) for f in feats for r in rings(f) for c in r]
minx = min(p[0] for p in pts); maxx = max(p[0] for p in pts)
miny = min(p[1] for p in pts); maxy = max(p[1] for p in pts)
scale = min((W - 2 * PAD) / (maxx - minx), (H - 2 * PAD) / (maxy - miny))
offx = (W - (maxx - minx) * scale) / 2
offy = (H - (maxy - miny) * scale) / 2


def to_px(lon, lat, ss=1):
    x, y = proj(lon, lat)
    return ((x - minx) * scale + offx) * ss, ((y - miny) * scale + offy) * ss


obl = [f["properties"]["oblast"] for f in feats]
cityIdx = [i for i in range(N) if obl[i] in (KYIV, SEVAS)]

img = Image.new("L", (W * SS, H * SS), BG)
d = ImageDraw.Draw(img)
for i in sorted(range(N), key=lambda i: i in cityIdx):   # міста-області — поверх
    for r in rings(feats[i]):
        d.polygon([to_px(lon, lat, SS) for lon, lat in r], fill=i)

small = Image.new("L", (W, H), BG)
px = small.load(); big = img.load()
for y in range(H):
    for x in range(W):
        cnt = {}
        for dy in range(SS):
            for dx in range(SS):
                v = big[x * SS + dx, y * SS + dy]
                cnt[v] = cnt.get(v, 0) + 1
        city = [c for c in cityIdx if cnt.get(c, 0) >= 3]
        px[x, y] = city[0] if city else max(cnt, key=cnt.get)

# межі: піксель, у якого правий/нижній сусід (або фон довкола) інший
src = small.copy(); s = src.load()
for y in range(H):
    for x in range(W):
        v = s[x, y]
        if v == BG:
            continue
        mark = None
        for nx, ny in ((x + 1, y), (x, y + 1), (x - 1, y), (x, y - 1)):
            nv = s[nx, ny] if 0 <= nx < W and 0 <= ny < H else BG
            if nv == v:
                continue
            if nv == BG:
                mark = BORDER; break
            if (nx, ny) not in ((x + 1, y), (x, y + 1)):
                continue
            if v in cityIdx or nv in cityIdx:
                continue           # не «з'їдаємо» крихітні міста
            if obl[nv] != obl[v]:
                mark = BORDER; break
            mark = mark or RBORDER
        if mark:
            px[x, y] = mark

# прев'ю у кольорах прошивки (приклад: дрони по Полтавщині, ракети — Кременчуцький р-н, частково — Київщина)
def hexc(h): return ((h >> 16) & 255, (h >> 8) & 255, h & 255)
demo = {}
for i in range(N):
    if obl[i] == 16: demo[i] = 0xD4A72C
    if obl[i] == 10: demo[i] = 0x7C6526
    if feats[i]["properties"]["name"] == "Кременчуцький": demo[i] = 0xE5484D
    if obl[i] == 0: demo[i] = 0xE5484D
pal = Image.new("RGB", (W, H)); pp = pal.load()
for y in range(H):
    for x in range(W):
        v = px[x, y]
        pp[x, y] = hexc(0x0B0F14 if v == BG else 0x5E6C7E if v == BORDER else 0x18202A if v == RBORDER else demo.get(v, 0x263445))
pal.resize((W * 3, H * 3), Image.NEAREST).save(os.path.join(ROOT, "docs", "map_preview.png"))

runs, offsets = [], []
for y in range(H):
    offsets.append(len(runs))
    x = 0
    while x < W:
        v = px[x, y]; n = 1
        while x + n < W and px[x + n, y] == v and n < 255:
            n += 1
        runs.append((n, v)); x += n
offsets.append(len(runs))

sx = [0] * 27; sy = [0] * 27; c = [0] * 27
for y in range(H):
    for x in range(W):
        v = px[x, y]
        if v < N:
            o = obl[v]; sx[o] += x; sy[o] += y; c[o] += 1
missing = [feats[i]["properties"]["name"] for i in range(N) if not any(v == i for row in [[px[x, y] for x in range(W)] for y in range(H)] for v in row)]

with open(os.path.join(ROOT, "include", "map_meta.h"), "w", encoding="utf-8") as f:
    f.write("// AUTO-GENERATED by tools/gen_map.py - do not edit\n#pragma once\n#include <stdint.h>\n")
    f.write(f"#define MAP_W {W}\n#define MAP_H {H}\n#define MAP_BG {BG}\n#define MAP_BORDER {BORDER}\n#define MAP_RBORDER {RBORDER}\n")
    f.write(f"#define MAP_REGION_COUNT {N}\n")
    f.write(f"#define MAP_PROJ_MINX {minx:.6f}f\n#define MAP_PROJ_MINY {miny:.6f}f\n#define MAP_PROJ_SCALE {scale:.6f}f\n"
            f"#define MAP_PROJ_OFFX {offx:.3f}f\n#define MAP_PROJ_OFFY {offy:.3f}f\n#define MAP_PROJ_COSLAT {math.cos(math.radians(LAT0)):.6f}f\n")
    f.write("// райони: індекс області (порядок alerts.in.ua IoT / OBLASTS), UID alerts.in.ua (0 — немає), назва\n")
    f.write("struct MapRegion { uint8_t oblast; uint16_t uid; const char* name; };\n")
    f.write("extern const MapRegion MAP_REGIONS[MAP_REGION_COUNT];\n")
    f.write(f"extern const uint16_t MAP_ROW_OFS[{len(offsets)}];\nextern const uint8_t MAP_RUNS[{len(runs) * 2}];\n")
    f.write("extern const int16_t MAP_CENTROID[27][2];\n")

with open(os.path.join(ROOT, "include", "map_data.h"), "w", encoding="utf-8") as f:
    f.write("// AUTO-GENERATED by tools/gen_map.py - do not edit. Include ONLY from src/mapdata.cpp\n#pragma once\n#include \"map_meta.h\"\n")
    f.write("// Геометрія: OCHA COD-AB Ukraine (HDX cod-ab-ukr), CC BY 3.0 IGO\n")
    f.write("const MapRegion MAP_REGIONS[MAP_REGION_COUNT] = {\n")
    for ft in feats:
        p = ft["properties"]
        nm = p["name"] if p["oblast"] in (KYIV, SEVAS) or "зона" in p["name"] else p["name"] + " район"
        f.write(f'  {{{p["oblast"]}, {p["uid"]}, "{nm}"}},\n')
    f.write("};\n")
    f.write(f"const uint16_t MAP_ROW_OFS[{len(offsets)}] = {{" + ",".join(map(str, offsets)) + "};\n")
    f.write(f"const uint8_t MAP_RUNS[{len(runs) * 2}] = {{\n")
    for i in range(0, len(runs), 16):
        f.write("  " + ",".join(f"{n},{v}" for n, v in runs[i:i + 16]) + ",\n")
    f.write("};\n")
    f.write("const int16_t MAP_CENTROID[27][2] = {" + ",".join(
        f"{{{sx[i] // max(c[i], 1)},{sy[i] // max(c[i], 1)}}}" for i in range(27)) + "};\n")
json.dump([{"oblast": ft["properties"]["oblast"], "uid": ft["properties"]["uid"], "name": ft["properties"]["name"],
            "pcode": ft["properties"]["pcode"]} for ft in feats],
          open(os.path.join(ROOT, "data", "regions.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=0)

# район для кожного міста з data/locations.json (point-in-polygon по геометрії)
def inside(lon, lat, ring):
    c = False
    for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]):
        if (y1 > lat) != (y2 > lat) and lon < (x2 - x1) * (lat - y1) / (y2 - y1) + x1:
            c = not c
    return c


loc = json.load(open(os.path.join(ROOT, "data", "locations.json"), encoding="utf-8"))
cr = {}
for ci in loc["cities"]:
    hit = [i for i in range(N) if any(inside(ci["lon"], ci["lat"], r) for r in rings(feats[i]))]
    hit = [i for i in hit if obl[i] == ci["oblast"]] or hit
    if not hit:  # найближчий центроїд у тій же області
        hit = sorted((i for i in range(N) if obl[i] == ci["oblast"]), key=lambda i: min(
            (lon - ci["lon"]) ** 2 + (lat - ci["lat"]) ** 2 for r in rings(feats[i]) for lon, lat in r))[:1]
    cr[ci["id"]] = hit[0] if hit else -1
json.dump(cr, open(os.path.join(ROOT, "data", "city_regions.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
print("cities:", {k: feats[v]["properties"]["name"] for k, v in cr.items()})
print("regions:", N, "runs:", len(runs), "bytes:", len(runs) * 2 + len(offsets) * 2, "missing on raster:", missing)
